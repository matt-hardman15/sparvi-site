"""Writing site data. Every sport's export goes through these, so encoding, rounding,
and schema checks are handled once.

- write_records: a DataFrame -> compact JSON array, validated against what the pages read
- write_json:    any object -> JSON
- write_numbers: the numbers quoted in article prose -> site/_generated/<sport>.yml, which
                 Quarto merges into every page so prose can use {{< meta <sport>.<key> >}}
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import pandas as pd

from sparvi.config import ROOT

GENERATED = ROOT / "site" / "_generated"


class SchemaError(ValueError):
    pass


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Always UTF-8: Windows defaults to cp1252, which garbles accented names (José).
    path.write_text(text, encoding="utf-8", newline="\n")


def write_json(path: Path, obj, indent: int | None = None) -> None:
    sep = None if indent else (",", ":")
    _write(path, json.dumps(obj, indent=indent, separators=sep, ensure_ascii=False))


def write_records(
    path: Path,
    df: pd.DataFrame,
    *,
    required: list[str],
    not_null: list[str] = (),
    min_rows: int = 1,
    digits: dict[str, int] | None = None,
) -> None:
    """Validate, round, and write a table the site reads.

    `required` lists every column a page uses. A renamed upstream column fails here,
    at build time, instead of rendering a blank chart in production.
    """
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise SchemaError(f"{path.name}: missing columns {missing}")
    if len(df) < min_rows:
        raise SchemaError(f"{path.name}: {len(df)} rows, expected at least {min_rows}")
    for c in not_null:
        n = int(df[c].isna().sum())
        if n:
            raise SchemaError(f"{path.name}: {n} null values in '{c}'")
    df = df.copy()
    for col, d in (digits or {}).items():
        if col in df:
            df[col] = df[col].round(d)
    records = df.replace({np.nan: None}).to_dict(orient="records")
    write_json(path, records)
    print(f"{path.name:<28} {len(df):>7,} rows  {path.stat().st_size / 1024:>6.0f} KB")


def _yaml_scalar(v) -> str:
    if isinstance(v, float) and not math.isfinite(v):
        raise SchemaError(f"non-finite number in prose numbers: {v}")
    return json.dumps(str(v), ensure_ascii=False)  # JSON strings are valid YAML


def write_numbers(sport: str, numbers: dict[str, object], source: str) -> Path:
    """Write the prose numbers for one sport. Values are pre-formatted strings."""
    lines = [f"# Generated by {source}. Do not edit; re-run the export.", f"{sport}:"]
    for k in sorted(numbers):
        lines.append(f"  {k}: {_yaml_scalar(numbers[k])}")
    path = GENERATED / f"{sport}.yml"
    _write(path, "\n".join(lines) + "\n")
    print(f"{path.name:<28} {len(numbers):>7} prose numbers")
    return path
